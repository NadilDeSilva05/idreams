import { GroupedSmartphone } from "@/types/smartphone";

export function getGroupedSmartphones(): GroupedSmartphone[] {
  const groupedMap = new Map<string, GroupedSmartphone>();

  for (const item of smartphoneProducts) {
    const key = `${item.brand}:::${item.model}`;
    if (!groupedMap.has(key)) {
      groupedMap.set(key, {
        brand: item.brand,
        model: item.model,
        category: item.category,
        variants: [],
      });
    }
    const group = groupedMap.get(key)!;
    if (!group.variants.some((v) => v.storage === item.storage)) {
      group.variants.push({
        storage: item.storage,
        price: item.price,
      });
    }
  }

  return Array.from(groupedMap.values());
}

export const groupedSmartphoneProducts = getGroupedSmartphones();

